DROP TABLE IF EXISTS VEHICLE CASCADE;
DROP TABLE IF EXISTS CUSTOMER CASCADE;
DROP TABLE IF EXISTS APP_USER CASCADE;

CREATE TABLE CUSTOMER (
    CustomerID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name VARCHAR(100) NOT NULL,
    Phone VARCHAR(20),
    Address VARCHAR(255),
    Email VARCHAR(100)
);

CREATE TABLE VEHICLE (
    VehicleID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PlateNumber VARCHAR(20) UNIQUE NOT NULL,
    Brand VARCHAR(50) NOT NULL,
    Model VARCHAR(50) NOT NULL,
    Year INT,
    CustomerID INT NOT NULL,
    FOREIGN KEY (CustomerID) REFERENCES CUSTOMER(CustomerID) ON DELETE CASCADE
);

CREATE TABLE EMPLOYEE (
    EmployeeID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name VARCHAR(100) NOT NULL,
    Phone VARCHAR(20),
    Position VARCHAR(50) NOT NULL
);

CREATE TABLE RECEPTIONIST (
    EmployeeID INT PRIMARY KEY,
    Shift VARCHAR(50),
    Languages VARCHAR(100),
    FOREIGN KEY (EmployeeID) REFERENCES EMPLOYEE(EmployeeID) ON DELETE CASCADE
);

CREATE TABLE MANAGER (
    EmployeeID INT PRIMARY KEY,
    Department VARCHAR(100),
    Bonus DECIMAL(10,2),
    FOREIGN KEY (EmployeeID) REFERENCES EMPLOYEE(EmployeeID) ON DELETE CASCADE
);

CREATE TABLE MECHANIC (
    EmployeeID INT PRIMARY KEY,
    Specialty VARCHAR(100),
    ExperienceYears INT,
    FOREIGN KEY (EmployeeID) REFERENCES EMPLOYEE(EmployeeID) ON DELETE CASCADE
);

CREATE TABLE APPOINTMENT (
    AppointmentID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AppointmentDate TIMESTAMP NOT NULL,
    Status VARCHAR(20) DEFAULT 'Pending',
    CustomerID INT NOT NULL,
    VehicleID INT NOT NULL,
    ReceptionistID INT NOT NULL,
    FOREIGN KEY (CustomerID) REFERENCES CUSTOMER(CustomerID) ON DELETE CASCADE,
    FOREIGN KEY (VehicleID) REFERENCES VEHICLE(VehicleID) ON DELETE CASCADE,
    FOREIGN KEY (ReceptionistID) REFERENCES RECEPTIONIST(EmployeeID) ON DELETE CASCADE
);

CREATE TABLE REPAIR (
    RepairID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProblemDescription TEXT,
    RepairDate TIMESTAMP NOT NULL,
    Cost DECIMAL(10,2),
    VehicleID INT NOT NULL,
    MechanicID INT NOT NULL,
    FOREIGN KEY (VehicleID) REFERENCES VEHICLE(VehicleID) ON DELETE CASCADE,
    FOREIGN KEY (MechanicID) REFERENCES MECHANIC(EmployeeID) ON DELETE CASCADE
);

CREATE TABLE INVOICE (
    InvoiceID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    InvoiceDate TIMESTAMP NOT NULL,
    TotalAmount DECIMAL(10,2) NOT NULL,
    RepairID INT UNIQUE NOT NULL,
    FOREIGN KEY (RepairID) REFERENCES REPAIR(RepairID) ON DELETE CASCADE
);

CREATE TABLE SPARE_PART (
    PartID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PartName VARCHAR(100) NOT NULL,
    Price DECIMAL(10,2) NOT NULL,
    StockQuantity INT DEFAULT 0
);

CREATE TABLE REPAIR_PART (
    RepairID INT NOT NULL,
    PartID INT NOT NULL,
    Quantity INT NOT NULL DEFAULT 1,
    PRIMARY KEY (RepairID, PartID),
    FOREIGN KEY (RepairID) REFERENCES REPAIR(RepairID) ON DELETE CASCADE,
    FOREIGN KEY (PartID) REFERENCES SPARE_PART(PartID) ON DELETE CASCADE
);

CREATE TABLE APP_USER (
    UserID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Username VARCHAR(100) UNIQUE NOT NULL,
    PasswordHash VARCHAR(255) NOT NULL,
    Role VARCHAR(20) NOT NULL CHECK (Role IN ('admin','user'))
);

